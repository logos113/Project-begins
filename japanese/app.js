/*
  주의! 표현 안에 < > & 같은 기호가 들어 있으면
  그대로 화면에 넣었을 때 HTML 태그로 잘못 해석되어 화면이 깨집니다.
  그래서 안전한 글자로 바꿔주는 과정이 꼭 필요합니다.
*/
function 안전한글자로(글) {
  return String(글 ?? "")
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");
}

// 상황 값("식당")을 보기 좋은 이름("식당 · 카페")으로 바꿉니다
function 상황이름(값) {
  const 찾음 = 상황목록.find((상황) => 상황.값 === 값);
  return 찾음 ? 찾음.이름 : 값;
}

/*
  발음 표기 줄(히라가나·로마자·한글음)을 만듭니다.
  화면 위쪽 '발음 표기' 설정에 따라 보여줄 줄이 달라집니다.
*/
function 발음줄_만들기(표현) {
  const 방식 = 발음표기_선택창 ? 발음표기_선택창.value : "all";
  const 줄들 = [];
  if (방식 === "all" || 방식 === "kana") {
    // 한자가 없는 문장은 일본어 원문과 읽기가 똑같아 두 번 나오게 됩니다. 그때는 생략합니다.
    if (표현.읽기 && 표현.읽기 !== 표현.일본어) {
      줄들.push(`<p class="kana">${안전한글자로(표현.읽기)}</p>`);
    }
  }
  if (방식 === "all") {
    줄들.push(`<p class="roma">${안전한글자로(표현.로마자)}</p>`);
  }
  if (방식 === "all" || 방식 === "korean") {
    줄들.push(`<p class="hangul">${안전한글자로(표현.한글음)}</p>`);
  }
  return 줄들.join("\n");
}

// 표현 하나를 카드 모양 HTML 글자로 만듭니다
function 카드_만들기(표현, 기록) {
  const 방식 = 연습방식_선택창 ? 연습방식_선택창.value : "뜻먼저";
  const 저장됨 = 기록.저장.includes(표현.아이디);
  const 상태 = 기록.익힘[표현.아이디];

  // 앞면(문제)에 무엇을 보여줄지 정합니다
  const 일본어먼저 = 방식 === "일본어먼저";
  const 바로보기   = 방식 === "바로보기";
  const 앞면 = 일본어먼저
    ? `<p class="jp">${안전한글자로(표현.일본어)}</p>`
    : `<p class="meaning-q">${안전한글자로(표현.뜻)}</p>`;

  // 이미 익힌 표현이면 언제 다시 볼지 작게 알려 줍니다
  const 진도표시 = 상태
    ? `<span class="due">복습 ${안전한글자로(상태.다음복습)}</span>`
    : `<span class="due new">새 표현</span>`;

  return `
    <article class="phrase-card${바로보기 ? " open" : ""}" data-id="${안전한글자로(표현.아이디)}">
      <div class="card-head">
        <span class="scene">${안전한글자로(상황이름(표현.상황))}</span>
        ${진도표시}
        <button class="star-btn${저장됨 ? " on" : ""}" data-act="save" type="button"
                aria-label="이 표현 저장하기" aria-pressed="${저장됨}">${저장됨 ? "★" : "☆"}</button>
      </div>

      <div class="card-front">
        ${앞면}
        ${바로보기 ? "" : `
        <button class="reveal-btn" data-act="reveal" type="button">
          ${일본어먼저 ? "뜻 확인하기" : "일본어 확인하기"}
        </button>`}
      </div>

      <div class="card-back"${바로보기 ? "" : " hidden"}>
        ${일본어먼저 ? "" : `<p class="jp">${안전한글자로(표현.일본어)}</p>`}
        ${발음줄_만들기(표현)}
        ${일본어먼저 ? `<p class="meaning">${안전한글자로(표현.뜻)}</p>` : ""}
        <p class="note">${안전한글자로(표현.메모)}</p>
        <div class="card-actions">
          <button class="btn-secondary" data-act="speak" type="button">🔊 발음 듣기</button>
          <button class="btn-primary" data-act="learned" type="button">외웠어요</button>
        </div>
      </div>
    </article>`;
}

// 화면 맨 위의 학습 상황(연속 일수 · 익힌 개수 · 복습할 개수)
