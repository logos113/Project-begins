/*
  연속 학습 일수(streak)를 갱신합니다.
  오늘 이미 공부했으면 그대로, 어제 공부했으면 +1, 그보다 오래 쉬었으면 1부터 다시.
*/
function 연속일수_갱신(기록) {
  const 오늘 = 오늘_날짜글자();
  if (기록.마지막학습일 === 오늘) return;          // 오늘은 이미 셌습니다
  const 어제 = 날짜_더하기(오늘, -1);
  기록.연속일수 = 기록.마지막학습일 === 어제 ? 기록.연속일수 + 1 : 1;
  기록.마지막학습일 = 오늘;
}

/*
  표현 하나의 복습 일정을 조정합니다.

  맞았나 = true  -> 다음 단계로 (간격이 벌어집니다)
  맞았나 = false -> 0단계로 (내일 다시 물어봅니다)
*/
function 복습_예약(아이디, 맞았나) {
  const 기록 = 기록_불러오기();
  const 이전 = 기록.익힘[아이디];
  const 단계 = 맞았나 ? Math.min((이전 ? 이전.단계 : -1) + 1, 복습_간격일.length - 1) : 0;
  const 오늘 = 오늘_날짜글자();

  기록.익힘[아이디] = {
    단계,
    마지막: 오늘,
    다음복습: 날짜_더하기(오늘, 복습_간격일[단계]),
  };
  연속일수_갱신(기록);
  기록_저장하기(기록);
  통계_그리기();
}

// 오늘 복습할 차례가 된 표현들을 모읍니다
function 복습할_표현들(기록 = 기록_불러오기()) {
  const 오늘 = 오늘_날짜글자();
  return 표현들.filter((표현) => {
    const 상태 = 기록.익힘[표현.아이디];
    // 다음복습 날짜가 오늘이거나 이미 지났으면 복습할 차례입니다
    return 상태 && 상태.다음복습 <= 오늘;
  });
}

// 저장(즐겨찾기) 넣고 빼기
function 저장_넣고빼기(아이디) {
  const 기록 = 기록_불러오기();
  const 자리 = 기록.저장.indexOf(아이디);
  if (자리 >= 0) 기록.저장.splice(자리, 1);
  else 기록.저장.push(아이디);
  기록_저장하기(기록);
  return 자리 < 0;   // true = 방금 저장됨
}


/* ==========================================================
   [9] 발음 듣기
   ------------------------------------------------------------
   브라우저에 들어 있는 '읽어주기' 기능(Web Speech API)을 씁니다.
   인터넷도, 회원가입도, 비용도 필요 없습니다.

   ※ 한자가 섞인 문장 대신 히라가나(읽기)를 읽힙니다.
      한자는 읽는 법이 여러 가지라 엉뚱하게 읽는 경우가 있기 때문입니다.
   ※ 아이폰·아이패드는 목소리 목록을 조금 늦게 준비합니다.
      그래서 목록이 비어 있으면 기본 목소리로라도 일단 읽게 해 둡니다.
   ========================================================== */

function 일본어_목소리_찾기() {
  if (!("speechSynthesis" in window)) return null;
  const 목소리들 = window.speechSynthesis.getVoices() || [];
  // 'ja-JP' 또는 'ja_JP' 처럼 표기가 제각각이라 앞 두 글자만 봅니다
  return 목소리들.find((목소리) => (목소리.lang || "").toLowerCase().startsWith("ja")) || null;
}

function 발음_듣기(표현) {
  if (!("speechSynthesis" in window)) {
    상태표시("이 브라우저는 발음 듣기를 지원하지 않습니다. 사파리나 크롬에서 열어보세요.", true);
    return;
  }
  window.speechSynthesis.cancel();          // 앞의 소리가 남아 있으면 끊습니다
  const 말 = new SpeechSynthesisUtterance(표현.읽기 || 표현.일본어);
  말.lang = "ja-JP";
  말.rate = 0.85;                            // 조금 느리게 — 따라 하기 좋도록
  const 목소리 = 일본어_목소리_찾기();
  if (목소리) 말.voice = 목소리;
  window.speechSynthesis.speak(말);
}

