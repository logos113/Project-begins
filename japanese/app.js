const 빈_기록 = () => ({ 익힘: {}, 저장: [], 연속일수: 0, 마지막학습일: "" });

function 기록_불러오기() {
  try {
    const 글 = localStorage.getItem(보관함_이름);
    if (!글) return 빈_기록();
    const 값 = JSON.parse(글);
    // 예전 형식이거나 일부가 빠져 있어도 앱이 멈추지 않도록 빈 값으로 채워둡니다
    return {
      익힘: 값.익힘 && typeof 값.익힘 === "object" ? 값.익힘 : {},
      저장: Array.isArray(값.저장) ? 값.저장 : [],
      연속일수: Number(값.연속일수) || 0,
      마지막학습일: 값.마지막학습일 || "",
    };
  } catch (오류) {
    // 저장 공간을 못 쓰는 경우(사파리 비공개 브라우징 등)에도 앱은 계속 돌아가야 합니다
    return 빈_기록();
  }
}

function 기록_저장하기(기록) {
  try {
    localStorage.setItem(보관함_이름, JSON.stringify(기록));
  } catch (오류) {
    상태표시("학습 기록을 저장하지 못했습니다. 비공개 브라우징 중이면 기록이 남지 않습니다.", true);
  }
}


