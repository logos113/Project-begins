// 오늘 날짜를 "2026-09-02" 형태의 글자로 만듭니다.
function 오늘_날짜글자(기준 = new Date()) {
  const 년 = 기준.getFullYear();
  const 월 = String(기준.getMonth() + 1).padStart(2, "0"); // 月은 0부터 시작해서 +1
  const 일 = String(기준.getDate()).padStart(2, "0");      // padStart = 한 자리면 앞에 0 붙이기
  return `${년}-${월}-${일}`;
}

/*
  "2026-09-02" 에 며칠을 더한 날짜글자를 돌려줍니다.

  ※ 문자열을 직접 계산하면 안 됩니다. 월말·윤년이 어긋납니다.
     날짜 객체로 바꾼 뒤 날짜를 더하면 브라우저가 알아서 넘겨줍니다.
     Date 에 "2026-09-02" 를 그대로 넣으면 세계표준시로 읽혀 하루가 밀릴 수 있어,
     숫자로 쪼개어 넣습니다.
*/
function 날짜_더하기(날짜글자, 더할일수) {
  const [년, 월, 일] = 날짜글자.split("-").map(Number);
  const 날 = new Date(년, 월 - 1, 일 + 더할일수);
  return 오늘_날짜글자(날);
}

// 화면 맨 위에 "2026년 9월 2일 화요일" 처럼 보여줍니다
function 오늘날짜_그리기() {
  if (!오늘날짜_자리) return;
  오늘날짜_자리.textContent = new Date().toLocaleDateString("ko-KR", {
    year: "numeric", month: "long", day: "numeric", weekday: "long",
  });
}


/* ==========================================================
   [6] 순서 섞기 — 날마다 다른 표현이 나오도록
   ------------------------------------------------------------
   그냥 목록 앞에서부터 3개씩 꺼내면 순서가 늘 똑같습니다.
   그렇다고 완전히 무작위로 뽑으면, 화면을 새로 고칠 때마다 표현이 바뀌어
   "오늘의 3개" 라는 말이 무색해집니다.

   그래서 '날짜'를 재료로 섞습니다.
   같은 날에는 몇 번을 열어도 같은 3개가 나오고, 날이 바뀌면 다른 3개가 나옵니다.

   아래 계산법(FNV-1a)은 논문 앱에서 쓴 것과 같습니다.
   날짜가 하루 넘어가 글자 하나만 달라져도 결과가 완전히 달라지도록 만들어져 있어서,
   특정 표현만 계속 안 나오는 일이 생기지 않습니다.
   ========================================================== */

function 섞기값(이름, 시드) {
  const 글 = 시드 + "#" + 이름;      // 날짜를 앞에 두어야 이후 계산 전체가 달라집니다
  let h = 2166136261;
  for (let i = 0; i < 글.length; i++) {
    h ^= 글.charCodeAt(i);           // ^ 는 비트를 뒤집어 섞는 연산입니다
    h = Math.imul(h, 16777619);      // Math.imul = 큰 수를 정확히 곱하는 함수
  }
  h ^= h >>> 16; h = Math.imul(h, 2246822507);
  h ^= h >>> 13; h = Math.imul(h, 3266489909);
  h ^= h >>> 16;
  return (h >>> 0) / 4294967296;     // 0 이상 1 미만
}

// 목록을 시드(날짜 등)에 따라 뒤섞은 새 목록을 돌려줍니다
function 섞기(목록, 시드) {
  return [...목록]
    .map((항목, i) => ({ 항목, 점수: 섞기값(항목.아이디 ?? String(i), 시드) }))
    .sort((가, 나) => 가.점수 - 나.점수)
    .map((칸) => 칸.항목);
}


