/*
  고르는 규칙은 세 가지입니다.

   1) 아직 안 본 표현을 먼저 — 매일 새로운 것을 배우게 됩니다.
   2) 쉬운 것(난이도 1)부터 — 'すみません' 을 모르는 채로 존댓말 문장을 배우면 소용이 없습니다.
   3) 상황이 겹치지 않게 — 하루에 식당 표현만 3개보다, 식당·전철·호텔 하나씩이 낫습니다.

   ※ 전부 익히고 나면 규칙 1)에 맞는 표현이 없어집니다.
      그때는 이미 본 표현 중에서 다시 골라 계속 굴러가게 합니다.
      "더 볼 표현이 없다"며 멈춰버리면 곤란하니까요.
*/
function 오늘의_표현_고르기(후보들, 시드, 기록) {
  if (후보들.length === 0) return [];

  const 안본것 = 후보들.filter((표현) => !기록.익힘[표현.아이디]);
  const 본것   = 후보들.filter((표현) => 기록.익힘[표현.아이디]);

  // 안 본 것을 앞에, 본 것을 뒤에 둔 하나의 줄을 만듭니다.
  // 각 덩어리 안에서는 '쉬운 것 먼저 + 날짜에 따라 섞기' 순서를 적용합니다.
  const 줄세우기 = (묶음) =>
    섞기(묶음, 시드).sort((가, 나) => (가.난이도 || 1) - (나.난이도 || 1));
  const 전체줄 = [...줄세우기(안본것), ...줄세우기(본것)];

  // 상황이 겹치지 않게 앞에서부터 뽑습니다
  const 고른것 = [];
  const 쓴상황 = new Set();
  for (const 표현 of 전체줄) {
    if (고른것.length >= 하루_표현수) break;
    if (쓴상황.has(표현.상황)) continue;
    고른것.push(표현);
    쓴상황.add(표현.상황);
  }

  // 상황이 겹치지 않는 것만으로 3개를 못 채웠다면(예: 한 상황만 골라 봤을 때)
  // 겹쳐도 좋으니 앞에서부터 채웁니다
  for (const 표현 of 전체줄) {
    if (고른것.length >= 하루_표현수) break;
    if (!고른것.includes(표현)) 고른것.push(표현);
  }
  return 고른것;
}

// 지금 화면 설정(상황 선택)에 해당하는 표현들만 골라냅니다
