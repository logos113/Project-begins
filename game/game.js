// 화면 오른쪽 위의 미사일 개수와, 아래쪽 발사 버튼을 상황에 맞게 보였다 감췄다 합니다
/*
  화면 위의 '지금 걸려 있는 효과' 와 아래쪽 발사 버튼을 상황에 맞게 고칩니다.
  강화·무적은 남은 시간을 초로 보여줍니다 (60 장면 = 1초).
*/
function 상태표시_갱신() {
  if (버프_자리) {
    const 조각 = [];
    /*
      기본이 아닌 무기를 들고 있으면 맨 앞에 보여줍니다 (다치면 사라집니다).

      긴 이름("연발 미사일") 대신 짧은 이름(무기 열쇠 = "연발")을 씁니다.
      세로로 든 휴대폰(가로 360px)에서는 점수·최고·♥ 와 나란히 놓이는데,
      긴 이름을 넣었더니 '점수' 가 두 줄로 접혔습니다.
    */
    if (무기 !== "기본") 조각.push(`${지금무기().그림} ${무기}`);
    /*
      강화는 보스전에서만 흐르므로, 품고만 있는 동안에는 그렇다고 알려줍니다.
      숫자가 안 줄어드는 것을 보고 '고장났나' 싶지 않도록요.
    */
    if (강화남음 > 0) {
      조각.push(싸우는중()
        ? `🔷 강화 ${Math.ceil(강화남음 / 60)}초`
        : `🔷 강화 ${Math.ceil(강화남음 / 60)}초 보관`);
    }
    if (로봇.무적 > 0) 조각.push(`⭐ 무적 ${Math.ceil(로봇.무적 / 60)}초`);
    버프_자리.textContent = 조각.join("  ");
    if (버프상자) 버프상자.hidden = 조각.length === 0;
  }
  // 싸우는 동안에만 발사·걷기 버튼이 나옵니다 (무기 고르는 중에는 감춥니다)
  const 싸움버튼_보이나 = 진행중 && !고르는중() && 싸우는중();
  if (발사버튼) {
    발사버튼.hidden = !싸움버튼_보이나;
    // 채우는 중에는 눌러도 안 나간다는 것을 흐리게 보여줍니다
    발사버튼.classList.toggle("empty", 재장전남음 > 0);
  }
  if (걷기버튼들) {
    걷기버튼들.hidden = !싸움버튼_보이나;
    // 버튼이 사라지는데 눌린 상태로 남아 있으면 로봇이 혼자 계속 걸어갑니다
    if (!싸움버튼_보이나) 걷기_모두_떼기();
  }
}

