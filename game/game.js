/* ---------- 점프 ---------- */

function 점프하기() {
  if (!진행중) return;

  const 땅에있나 = 로봇.y >= 땅위치 - 0.5;
  const 최대점프횟수 = 설정.두번_점프_가능 ? 2 : 1;

  if (로봇.점프한횟수 < 최대점프횟수) {
    로봇.세로속도 = -설정.점프_힘;
    로봇.점프한횟수 += 1;
    if (로봇.점프한횟수 === 1) 점프소리();
    else 두번점프();
  }
}


