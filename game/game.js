/*
  아이템을 먹었을 때 무슨 일이 일어나는가.

    강화  한동안 미사일이 두 배로 세지고 더 빨리 나갑니다
    무적  한동안 아무것도 맞지 않습니다 (로봇이 깜빡입니다)
    회복  체력을 한 칸 채웁니다. 이미 가득이면 대신 점수를 줍니다
          (안 그러면 체력이 가득일 때 먹는 것이 아무 쓸모가 없습니다)
*/
function 아이템_먹었을때(아이템) {
  아이템소리();

  if (아이템.종류 === "강화") {
    강화남음 = 설정.강화_시간;
    터뜨리기(아이템.x, 아이템.y, 10, 설정.색.아이템강화);
    const 초 = Math.round(설정.강화_시간 / 60);
    // 싸우는 중에 주우면 바로, 달리는 중에 주우면 보스를 만날 때까지 품고 갑니다
    알림띄우기(싸우는중()
      ? `미사일 강화!  ${초}초 동안 두 배`
      : `미사일 강화를 챙겼습니다!  보스전에서 ${초}초`, 90);

  } else if (아이템.종류 === "무적") {
    로봇.무적 = Math.max(로봇.무적, 설정.무적아이템_시간);
    터뜨리기(아이템.x, 아이템.y, 10, 설정.색.아이템무적);
    알림띄우기(`무적!  ${Math.round(설정.무적아이템_시간 / 60)}초 동안 안 맞아요`, 90);

  } else {
    if (로봇.체력 < 설정.로봇_체력) {
      로봇.체력 = Math.min(로봇.체력 + 설정.회복량, 설정.로봇_체력);
      하트_그리기();
      알림띄우기(`체력 회복!  ♥ ${로봇.체력}칸`, 90);
    } else {
      점수 += 설정.회복_가득할때_점수;
      알림띄우기(`체력이 가득!  대신 +${설정.회복_가득할때_점수}점`, 90);
    }
    터뜨리기(아이템.x, 아이템.y, 10, 설정.색.아이템회복);
  }

  상태표시_갱신();
}

/* ==========================================================
   성과 마법사
   ------------------------------------------------------------
   보스와 보스 사이 한가운데쯤에서 성이 다가옵니다.

     다가옴 — 성이 왼쪽으로 흘러오고, 로봇은 계속 달립니다
     고르기 — 로봇이 성 앞에 멈춰 서고 마법사가 나옵니다.
              이 동안에는 게임이 통째로 멈춥니다 (아래 한장면_그리기 참고)
     떠남   — 고르고 나면 성이 지나가고, 다시 장애물이 나옵니다

   ※ 멈추기 전에 '로봇이 땅에 있는지' 를 봅니다.
      뛰어오른 순간에 멈춰버리면 로봇이 공중에 붕 떠 있게 됩니다.
   ========================================================== */

function 고르는중() {
  return !!성 && 성.단계 === "고르기";
}

/* 보스와 '실제로' 싸우고 있는 동안인가 (날아 들어오거나 나가는 중은 아닙니다) */
function 싸우는중() {
  return !!보스 && 보스.단계 === "싸움";
}

/*
  세상이 흘러가는 빠르기.

  거인과 맞붙는 동안에는 0 입니다 — 달리기를 멈추고 그 자리에서 싸웁니다.
  그 대신 로봇이 좌우로 걸어 다닐 수 있습니다 (설정.옆걸음_속도).

  ※ '속도' 자체는 건드리지 않습니다.
     속도는 스테이지가 얼마나 빠른지를 나타내는 값이라, 거인이 던지는
     돌의 빠르기와 화면 표시에도 쓰입니다. 그걸 0 으로 만들면 싸우는 동안
     돌이 제자리에 멈춰 섭니다.
*/
function 흐름속도() {
  return 싸우는중() ? 0 : 속도;
}

/*
  한국어 조사 고르기 — 앞 글자에 받침이 있으면 '을', 없으면 '를'.

  한글은 글자 하나하나가 44032(가) 부터 차례로 번호를 갖습니다.
  그 번호에서 44032 를 빼고 28 로 나눈 나머지가 받침 번호인데,
  0 이면 받침이 없다는 뜻입니다.

    폭탄 → '탄' 에 받침 ㄴ 이 있음  → 폭탄을
    레이저 → '저' 에 받침이 없음   → 레이저를
*/
function 을를(말) {
  const 끝 = 말.charCodeAt(말.length - 1);
  if (끝 < 44032 || 끝 > 55203) return "을(를)";      // 한글이 아니면 둘 다 보여줍니다
  return (끝 - 44032) % 28 === 0 ? "를" : "을";
}

