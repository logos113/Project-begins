/*
  로봇을 좌우로 움직입니다.

  거인과 싸우는 동안에만 걸을 수 있습니다. 그때는 세상이 멈춰 있어서
  (흐름속도 참고) 로봇이 직접 움직이지 않으면 거인에게 다가갈 수가 없습니다.
  칼처럼 코앞을 베는 무기는 이게 없으면 쓸 수가 없습니다.

  싸움이 끝나면 원래 자리(설정.로봇_제자리x)로 스르르 돌아옵니다.
  툭 하고 순간이동하면 보기 나쁘기 때문입니다.
*/
function 로봇_좌우움직이기(dt) {
  if (싸우는중()) {
    const 방향 = (걷기.오른 ? 1 : 0) - (걷기.왼 ? 1 : 0);
    if (방향 !== 0) 로봇.x += 방향 * 설정.옆걸음_속도 * dt;

    // 거인 몸을 뚫고 지나가지 못하게 막습니다
    const 오른끝 = 보스.x - 보스.폭 / 2 - 로봇.폭 - 2;
    로봇.x = Math.max(설정.옆걸음_왼끝, Math.min(로봇.x, 오른끝));
    return;
  }

  // 싸울 때가 아니면 제자리로 돌아옵니다
  const 제자리 = 설정.로봇_제자리x;
  if (로봇.x !== 제자리) {
    로봇.x += (제자리 - 로봇.x) * 0.1 * dt;
    if (Math.abs(로봇.x - 제자리) < 0.5) 로봇.x = 제자리;
  }
}

function 점프하기() {
  if (!진행중) return;
  // 성 앞에서 무기를 고르는 동안에는 점프하지 않습니다
  if (고르는중()) return;

  const 땅에있나 = 로봇.y >= 땅위치 - 0.5;
  const 최대점프횟수 = 설정.두번_점프_가능 ? 2 : 1;

  if (로봇.점프한횟수 < 최대점프횟수) {
    로봇.세로속도 = -설정.점프_힘;
    로봇.점프한횟수 += 1;
    if (로봇.점프한횟수 === 1) 점프소리();
    else 두번점프();
  }
}


