/*
  아이템 한 개를 띄웁니다.

  종류는 설정.아이템_비율 대로 무작위로 정합니다.
  비율이 { 강화: 4, 무적: 2, 회복: 3 } 이면 합이 9 이므로
  0~9 사이의 수를 뽑아 4 미만이면 강화, 6 미만이면 무적, 나머지는 회복입니다.

  높이는 두 가지입니다.
    보통 — 한 번 점프로 닿습니다
    높음 — 두 번 점프를 해야 닿습니다 (설정.높은아이템_확률)
  로봇은 한 번 점프로 110px, 두 번이면 220px 까지 오릅니다.
  그 사이에 두면 '두 번 점프해야만 닿는 자리' 가 됩니다.
*/
function 아이템_종류_뽑기() {
  const 비율 = 설정.아이템_비율;
  const 합 = 비율.강화 + 비율.무적 + 비율.회복;
  const 뽑은수 = Math.random() * 합;
  if (뽑은수 < 비율.강화) return "강화";
  if (뽑은수 < 비율.강화 + 비율.무적) return "무적";
  return "회복";
}

