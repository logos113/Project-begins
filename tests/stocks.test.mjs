let 실패 = 0;
const 검사 = (이름, 조건, 실제) => {
  console.log(`${조건 ? "✅" : "❌"} ${이름}${조건 ? "" : "\n     실제값: " + JSON.stringify(실제)}`);
  if (!조건) 실패 += 1;
};

/* ==========================================================
   1) RSS 글자 벗겨내기
   ------------------------------------------------------------
   RSS 안에서는 & 와 < 를 그대로 쓸 수 없어서 &amp; &lt; 로 바꿔 적습니다.
   안 벗기면 화면에 "삼성전자&amp;LG" 라고 그대로 나옵니다.
   ========================================================== */
검사("CDATA 껍질을 벗기는가",
  글_다듬기("<![CDATA[삼성전자 신고가]]>") === "삼성전자 신고가",
  글_다듬기("<![CDATA[삼성전자 신고가]]>"));

검사("&amp; 를 & 로 되돌리는가",
  글_다듬기("삼성전자&amp;LG") === "삼성전자&LG",
  글_다듬기("삼성전자&amp;LG"));

/*
  ※ & 를 맨 마지막에 되돌려야 합니다.
     먼저 되돌리면 "&amp;lt;" 가 "&lt;" 가 되었다가 다시 "<" 로 풀려서,
     글쓴이가 일부러 적은 "&lt;" 가 사라집니다.
*/
검사("이중으로 피한 글자를 한 번만 푸는가",
  글_다듬기("코스피 &amp;lt; 코스닥") === "코스피 &lt; 코스닥",
  글_다듬기("코스피 &amp;lt; 코스닥"));

검사("본문에 섞인 꺾쇠를 떼는가",
  글_다듬기("<p>코스피 <b>2,500</b> 돌파</p>") === "코스피 2,500 돌파",
  글_다듬기("<p>코스피 <b>2,500</b> 돌파</p>"));

검사("숫자로 적은 글자(&#39;)를 푸는가",
  글_다듬기("오늘의 &#39;주도주&#39;") === "오늘의 '주도주'",
  글_다듬기("오늘의 &#39;주도주&#39;"));

검사("여러 칸 띄어쓰기를 하나로 모으는가",
  글_다듬기("코스피   상승\n\n  마감") === "코스피 상승 마감",
  글_다듬기("코스피   상승\n\n  마감"));

/* 날짜 읽기 — RSS 마다 적는 법이 다릅니다 */
