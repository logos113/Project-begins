/* 아무 달이나 골라도 요일이 맞아야 합니다 */
let 요일다맞나 = true;
for (let 달 = 1; 달 <= 12; 달 += 1) {
  for (const [요일번호, 이름] of [[5, "금"], [4, "목"], [1, "월"]]) {
    for (let 번째 = 1; 번째 <= 4; 번째 += 1) {
      const 날 = 몇번째_요일(2026, 달, 요일번호, 번째);
      if (날 && !요일맞나(날, 이름)) 요일다맞나 = false;
      if (날 && 날.getUTCMonth() !== 달 - 1) 요일다맞나 = false;   // 달을 넘지 않아야 합니다
    }
  }
}
검사("2026년 열두 달 전부 요일 계산이 맞는가", 요일다맞나);

