// 논문 앱에서 이 실수로 head 가 통째로 비어버린 적이 있습니다.
const 주석중첩 = (글, 열기, 닫기) => {
  const i = 글.indexOf(열기);
  if (i < 0) return false;
  const 안쪽 = 글.slice(i + 열기.length, 글.indexOf(닫기, i + 열기.length));
  return 안쪽.includes(열기) || 안쪽.includes(닫기);
};
