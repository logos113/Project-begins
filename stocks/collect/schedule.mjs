/*
  한국 시간(KST)으로 날짜를 다룹니다.
  깃허브 일꾼은 영국 시간(UTC)에서 도는데, 그대로 쓰면
  한국 새벽 시간대에 하루가 어긋납니다.
*/
export function 한국날짜(때 = new Date()) {
  const 한국 = new Date(때.getTime() + 9 * 60 * 60 * 1000);
  return 한국.toISOString().slice(0, 10);   // "2026-11-05"
}

/* "2026-11-05" → Date (시간은 정오로 둬서 시간대 때문에 날이 밀리지 않게 합니다) */
function 날짜로(글) {
  return new Date(`${글}T12:00:00Z`);
}

function 글자로(때) {
  return 때.toISOString().slice(0, 10);
}

const 요일이름 = ["일", "월", "화", "수", "목", "금", "토"];

/* 그 달의 n번째 특정 요일 (예: 11월의 첫째 금요일) */
function 몇번째_요일(해, 달, 요일, 번째) {
  const 첫날 = new Date(Date.UTC(해, 달 - 1, 1, 12));
  const 첫요일 = 첫날.getUTCDay();
  const 더할날 = (요일 - 첫요일 + 7) % 7 + (번째 - 1) * 7;
  const 나온날 = new Date(Date.UTC(해, 달 - 1, 1 + 더할날, 12));
  // 달을 넘어가면 없는 날입니다 (예: 다섯째 금요일이 없는 달)
  return 나온날.getUTCMonth() === 달 - 1 ? 나온날 : null;
}

/* 그 달의 마지막 특정 요일 (예: 5월 마지막 월요일) */
function 마지막_요일(해, 달, 요일) {
  const 다음달첫날 = new Date(Date.UTC(해, 달, 1, 12));
  const 마지막날 = new Date(다음달첫날.getTime() - 24 * 60 * 60 * 1000);
  const 차이 = (마지막날.getUTCDay() - 요일 + 7) % 7;
  return new Date(마지막날.getTime() - 차이 * 24 * 60 * 60 * 1000);
}

/*
  규칙으로 확실히 계산되는 일정들.

  '확실히' 가 중요합니다. 여기 넣은 것은 전부 "매월 첫째 금요일" 처럼
  달력만 있으면 누구나 같은 답을 내는 것들입니다.
  "보통 그맘때" 인 것은 넣지 않았습니다.
*/
function 규칙일정(해, 달) {
  const 모은것 = [];
  const 넣기 = (때, 갈래, 이름, 설명 = "") => {
    if (때) 모은것.push({ 날짜: 글자로(때), 갈래, 이름, 설명, 출처: "규칙" });
  };

  // --- 미국 ---
  // 고용보고서(비농업 고용지표)는 매월 첫째 금요일에 나옵니다.
  넣기(몇번째_요일(해, 달, 5, 1), "미국", "미국 고용보고서",
       "비농업 신규고용·실업률. 밤 10시 30분(한국시간) 발표");

  // 쿼드러플 위칭 — 3·6·9·12월 셋째 금요일. 선물·옵션 네 가지가 한꺼번에 만기입니다.
  if ([3, 6, 9, 12].includes(달)) {
    넣기(몇번째_요일(해, 달, 5, 3), "미국", "미국 네 마녀의 날",
         "선물·옵션 동시 만기. 장 막판 변동성이 커집니다");
  }

  // --- 한국 ---
  // 코스피200 옵션 만기는 매월 두 번째 목요일입니다.
  const 둘째목요일 = 몇번째_요일(해, 달, 4, 2);
  if ([3, 6, 9, 12].includes(달)) {
    넣기(둘째목요일, "한국", "선물·옵션 동시 만기일",
         "분기 만기(네 마녀의 날). 수급이 크게 흔들릴 수 있습니다");
  } else {
    넣기(둘째목요일, "한국", "옵션 만기일", "코스피200 옵션 만기");
  }

  // --- 미국 증시 휴장 (날짜가 요일로 정해지는 것들) ---
  if (달 === 1) 넣기(몇번째_요일(해, 1, 1, 3), "휴장", "미국 증시 휴장", "마틴 루서 킹 데이");
  if (달 === 2) 넣기(몇번째_요일(해, 2, 1, 3), "휴장", "미국 증시 휴장", "대통령의 날");
  if (달 === 5) 넣기(마지막_요일(해, 5, 1), "휴장", "미국 증시 휴장", "메모리얼 데이");
  if (달 === 9) 넣기(몇번째_요일(해, 9, 1, 1), "휴장", "미국 증시 휴장", "노동절");
  if (달 === 11) 넣기(몇번째_요일(해, 11, 4, 4), "휴장", "미국 증시 휴장", "추수감사절");

  // 날짜가 고정된 휴장일
  const 고정휴장 = {
    "1-1": ["한·미 증시 휴장", "새해 첫날"],
    "3-1": ["한국 증시 휴장", "삼일절"],
    "5-5": ["한국 증시 휴장", "어린이날"],
    "6-6": ["한국 증시 휴장", "현충일"],
    "7-4": ["미국 증시 휴장", "독립기념일"],
    "8-15": ["한국 증시 휴장", "광복절"],
    "10-3": ["한국 증시 휴장", "개천절"],
    "10-9": ["한국 증시 휴장", "한글날"],
    "12-25": ["한·미 증시 휴장", "성탄절"],
  };
  for (const [날, [이름, 설명]] of Object.entries(고정휴장)) {
    const [ㄷ, ㅇ] = 날.split("-").map(Number);
    if (ㄷ === 달) 넣기(new Date(Date.UTC(해, 달 - 1, ㅇ, 12)), "휴장", 이름, 설명);
  }

  return 모은것;
}

/*
  calendar.json 에서 읽은 일정을 받습니다 (FOMC·금통위·CPI 같은 것).

  모양:
    [{ "날짜": "2026-12-16", "갈래": "미국", "이름": "FOMC 결과 발표", "설명": "..." }]

  없거나 비어 있으면 빈 목록을 돌려줍니다. 지어내지 않습니다.
*/
export function 등록일정_고르기(등록된것, 처음, 끝) {
  if (!Array.isArray(등록된것)) return [];
  return 등록된것
    .filter((ㅇ) => ㅇ && typeof ㅇ.날짜 === "string" && ㅇ.날짜 >= 처음 && ㅇ.날짜 <= 끝)
    .map((ㅇ) => ({
      날짜: ㅇ.날짜,
      갈래: ㅇ.갈래 || "기타",
      이름: ㅇ.이름 || "(이름 없음)",
      설명: ㅇ.설명 || "",
      출처: "등록",
    }));
}

/*
  오늘부터 며칠치 일정을 모읍니다.

  규칙으로 계산한 것과 calendar.json 에 등록된 것을 합쳐
  날짜순으로 늘어놓습니다.
*/
export function 일정_모으기(오늘글자, 등록된것, 며칠 = 14) {
  const 오늘 = 날짜로(오늘글자);
  const 끝날 = new Date(오늘.getTime() + (며칠 - 1) * 24 * 60 * 60 * 1000);
  const 끝글자 = 글자로(끝날);

  // 걸쳐 있는 달 전부에서 규칙 일정을 뽑습니다 (월말이면 다음 달까지 봐야 합니다)
  const 규칙모음 = [];
  const 본달 = new Set();
  for (let i = 0; i < 며칠; i += 1) {
    const 날 = new Date(오늘.getTime() + i * 24 * 60 * 60 * 1000);
    const 열쇠 = `${날.getUTCFullYear()}-${날.getUTCMonth() + 1}`;
    if (본달.has(열쇠)) continue;
    본달.add(열쇠);
    규칙모음.push(...규칙일정(날.getUTCFullYear(), 날.getUTCMonth() + 1));
  }

  const 전부 = [
    ...규칙모음.filter((ㅇ) => ㅇ.날짜 >= 오늘글자 && ㅇ.날짜 <= 끝글자),
    ...등록일정_고르기(등록된것, 오늘글자, 끝글자),
  ];

  전부.sort((ㄱ, ㄴ) => (ㄱ.날짜 < ㄴ.날짜 ? -1 : ㄱ.날짜 > ㄴ.날짜 ? 1 : 0));

  // 날짜마다 요일과 '며칠 뒤인지' 를 붙여둡니다 (앱에서 다시 계산하지 않게)
  return 전부.map((ㅇ) => {
    const 때 = 날짜로(ㅇ.날짜);
    const 남은날 = Math.round((때 - 오늘) / (24 * 60 * 60 * 1000));
    return {
      ...ㅇ,
      요일: 요일이름[때.getUTCDay()],
      남은날,
      오늘인가: 남은날 === 0,
      이번주인가: 남은날 >= 0 && 남은날 <= 6,
    };
  });
}

