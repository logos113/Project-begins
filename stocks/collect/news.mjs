/*
  ============================================================
  news.mjs  =  모아온 기사 추리기

  RSS 를 그대로 보여주면 아침에 읽을 수가 없습니다.
  세 가지를 걸러야 쓸 만해집니다.

    1) 오래된 것    RSS 에는 며칠 전 기사가 그대로 남아 있습니다
    2) 겹치는 것    같은 사건을 네 신문이 쓰면 네 번 보입니다
    3) 너무 많은 것 한 갈래에 50건이 뜨면 아무도 안 읽습니다

  이 세 가지를 하는 곳입니다. 네트워크를 쓰지 않는 '계산' 만 들어 있어서
  인터넷 없이도 검사할 수 있습니다 (tests/stocks.test.mjs).
  ============================================================
*/

/*
  너무 오래된 기사는 뺍니다.

  48시간으로 둔 이유: 주말과 연휴에는 새 기사가 거의 안 올라옵니다.
  24시간으로 자르면 월요일 아침 브리핑이 텅 비어버립니다.
*/
export const 봐줄_시간 = 48 * 60 * 60 * 1000;

/*
  제목에서 '비교용 열쇠' 를 만듭니다.

  같은 사건이라도 신문마다 제목이 조금씩 다릅니다.
    "삼성전자, 3분기 영업이익 10조...시장 전망 상회"
    "[속보] 삼성전자 3분기 영업이익 10조원"
  기호와 공백을 다 떼고 앞 40글자만 보면 꽤 많이 걸러집니다.

  ※ 완벽하지는 않습니다. 제목을 아주 다르게 쓴 기사는 둘 다 남습니다.
     더 똑똑하게 할 수도 있지만, 아침에 비슷한 기사 하나 더 보이는 것보다
     서로 다른 기사를 잘못 지워버리는 쪽이 훨씬 나쁩니다.
     그래서 일부러 느슨하게 두었습니다.
*/
export function 제목_열쇠(제목) {
  return String(제목 || "")
    .toLowerCase()
    .replace(/[^가-힣a-z0-9]/g, "")
    .slice(0, 40);
}

/*
  기사 목록을 추립니다. 새 것부터, 겹치는 것 빼고.

  지금  — 기준 시각(밀리초). 검사할 때 원하는 시각을 넣을 수 있게 밖에서 받습니다.
*/
export function 기사_추리기(기사들, 지금 = Date.now()) {
  const 본것 = new Set();
  const 남길것 = [];

  // 새 것부터 봅니다. 시각을 모르는 기사(때 === null)는 맨 뒤로 보냅니다.
  const 줄세운것 = [...기사들].sort((ㄱ, ㄴ) => {
    if (!ㄱ.때 && !ㄴ.때) return 0;
    if (!ㄱ.때) return 1;
    if (!ㄴ.때) return -1;
    return ㄱ.때 < ㄴ.때 ? 1 : -1;
  });

  for (const 기사 of 줄세운것) {
    if (기사.때) {
      const 지난시간 = 지금 - new Date(기사.때).getTime();
      if (지난시간 > 봐줄_시간) continue;
      /*
        시각이 미래인 기사는 버립니다.
        시간대를 잘못 적어 보내는 곳이 가끔 있는데, 그대로 두면
        그 기사가 영원히 맨 위에 붙어 있게 됩니다.
        다만 한 시간까지는 봐줍니다 — 서버 시계가 조금씩 어긋나니까요.
      */
      if (지난시간 < -60 * 60 * 1000) continue;
    }

    const 열쇠 = 제목_열쇠(기사.제목);
    if (!열쇠 || 본것.has(열쇠)) continue;
    본것.add(열쇠);
    남길것.push(기사);
  }

  return 남길것;
}

/*
  갈래("한국"·"미국"·"코인")별로 나눠 담고, 각각 추려서 개수를 자릅니다.
*/
export function 갈래별_정리(읽어온것들, 지금 = Date.now(), 갈래당 = 12) {
  const 담을곳 = { 한국: [], 미국: [], 코인: [] };

  for (const 하나 of 읽어온것들) {
    for (const 기사 of 하나.기사 || []) {
      if (담을곳[기사.갈래]) 담을곳[기사.갈래].push(기사);
    }
  }

  const 결과 = {};
  for (const [갈래, 기사들] of Object.entries(담을곳)) {
    결과[갈래] = 기사_추리기(기사들, 지금).slice(0, 갈래당);
  }
  return 결과;
}
